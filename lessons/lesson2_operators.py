"""
Lesson 2: Operators

In this lesson, I explored arithmetic, comparison, and logical operators in Python.
"""

# Arithmetic Operators
addition = 10 + 5
subtraction = 10 - 5

# Comparison Operators
is_greater = 10 > 5

# Logical Operators
and_result = (10 > 5) and (5 < 8)

print(f"10 + 5 = {addition}")
print(f"10 - 5 = {subtraction}")
print(f"Is 10 greater than 5? {is_greater}")
print(f"Is 10 > 5 AND 5 < 8? {and_result}")