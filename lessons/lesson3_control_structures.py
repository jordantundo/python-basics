# If-Else Statement
temperature = 30
if temperature > 25:
    print("It's a hot day!")
else:
    print("It's a cool day!")

# For Loop
for i in range(3):
    print(f"Counting: {i}")

# While Loop
counter = 0
while counter < 3:
    print(f"While counting: {counter}")
    counter += 1